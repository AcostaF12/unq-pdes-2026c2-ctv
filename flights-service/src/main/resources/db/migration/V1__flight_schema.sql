CREATE TABLE flights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline VARCHAR(120) NOT NULL, flight_date DATE NOT NULL, departure_time TIME NOT NULL,
    origin VARCHAR(3) NOT NULL, destination VARCHAR(3) NOT NULL,
    capacity INTEGER NOT NULL, availability INTEGER NOT NULL
);
CREATE TABLE flight_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id BIGINT NOT NULL REFERENCES flights(id), passenger_name VARCHAR(160) NOT NULL
);
